// Generates src/styles/tw-palette.css — the Tailwind palette as CSS variables.
//
// Light (:root) = the exact default Tailwind values, so pages without
// data-theme (public pages: weight logging, public food bank) look unchanged.
// Dark ([data-theme="dark"]) remaps every shade for the obsidian CRM theme.
//
// Two variable sets, because one Tailwind shade plays two roles:
//   --twc-*  backgrounds / borders / rings (bg-indigo-600 + text-white must stay saturated)
//   --twt-*  text (text-indigo-600 on a near-black surface must become lighter)
//
// Run: node scripts/gen-tw-palette.mjs   (from client/)

import { writeFileSync, mkdirSync } from 'node:fs';
import colors from 'tailwindcss/colors.js';

const HUES = ['gray', 'indigo', 'green', 'red', 'blue', 'yellow', 'orange', 'amber', 'teal', 'purple', 'lime', 'emerald', 'rose', 'pink', 'sky', 'violet'];
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const SURFACE = '#0F0F12';

const hexToRgb = (hex) => {
  const h = hex.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
};
const rgb = (hex) => hexToRgb(hex).join(' ');
const mix = (a, b, t) => {
  const [ra, ga, ba] = hexToRgb(a);
  const [rb, gb, bb] = hexToRgb(b);
  return [ra + (rb - ra) * t, ga + (gb - ga) * t, ba + (bb - ba) * t].map(Math.round).join(' ');
};

// Dark gray scale (zinc-based)
const DARK_GRAY_BG = {
  50: '#141418', 100: '#1A1A1F', 200: '#27272A', 300: '#3F3F46', 400: '#52525B',
  500: '#71717A', 600: '#A1A1AA', 700: '#3F3F46', 800: '#27272A', 900: '#18181B', 950: '#0F0F12',
};
const DARK_GRAY_TEXT = {
  50: '#FAFAFA', 100: '#F4F4F5', 200: '#E4E4E7', 300: '#D4D4D8', 400: '#8B8B94',
  500: '#A1A1AA', 600: '#C4C4CC', 700: '#D4D4D8', 800: '#E4E4E7', 900: '#FAFAFA', 950: '#FFFFFF',
};
// Tinted backgrounds for light shades (mix of the hue into the surface)
const BG_TINT = { 50: 0.10, 100: 0.16, 200: 0.26, 300: 0.42 };
// Text shade → which original shade to show on dark
const TEXT_MAP = { 50: 100, 100: 100, 200: 200, 300: 300, 400: 400, 500: 400, 600: 400, 700: 300, 800: 200, 900: 100, 950: 50 };

const light = [];
const dark = [];
for (const hue of HUES) {
  const pal = colors[hue];
  for (const s of SHADES) {
    light.push(`  --twc-${hue}-${s}: ${rgb(pal[s])};`, `  --twt-${hue}-${s}: ${rgb(pal[s])};`);
    if (hue === 'gray') {
      dark.push(`  --twc-gray-${s}: ${rgb(DARK_GRAY_BG[s])};`, `  --twt-gray-${s}: ${rgb(DARK_GRAY_TEXT[s])};`);
    } else {
      const bg = BG_TINT[s] !== undefined ? mix(SURFACE, pal[500], BG_TINT[s]) : rgb(pal[s]);
      dark.push(`  --twc-${hue}-${s}: ${bg};`, `  --twt-${hue}-${s}: ${rgb(pal[TEXT_MAP[s]])};`);
    }
  }
}
light.push('  --twc-surface: 255 255 255;');
dark.push(`  --twc-surface: ${rgb(SURFACE)};`);

const css = `/* GENERATED by scripts/gen-tw-palette.mjs — do not edit by hand. */
/* Light = default Tailwind palette (public pages). Dark = obsidian CRM theme. */
:root {
${light.join('\n')}
}

[data-theme="dark"] {
${dark.join('\n')}
}
`;
mkdirSync('src/styles', { recursive: true });
writeFileSync('src/styles/tw-palette.css', css);
console.log(`tw-palette.css: ${HUES.length} hues × ${SHADES.length} shades × 2 roles`);
